-- B0 baseline migration.
-- This migration mirrors the current JPA model only. Business-domain redesigns belong to B1+ migrations.

create table companies (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone,
    name varchar(255) not null,
    gstin varchar(255),
    pan_cin varchar(255),
    bank_details varchar(255),
    upi varchar(255),
    logo_path varchar(255),
    signatory varchar(255)
);

create table buildings (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone,
    code varchar(255) not null unique,
    name varchar(255) not null,
    address varchar(255),
    state varchar(255),
    municipal_number varchar(255),
    owner varchar(255),
    plot_area numeric(38,2),
    active boolean not null
);

create table charge_types (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone,
    name varchar(255) not null unique,
    sac_hsn_code varchar(255),
    unit varchar(255),
    default_description varchar(255),
    active boolean not null
);

create table customers (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone,
    code varchar(255) not null unique,
    name varchar(255) not null,
    contact varchar(255),
    state varchar(255),
    gstin varchar(255),
    pan varchar(255),
    opening_balance varchar(255),
    credit_days integer not null,
    tds_rate numeric(38,2),
    active boolean not null
);

create table document_counters (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone,
    document_type varchar(255) not null,
    financial_year varchar(255) not null,
    last_number bigint not null,
    constraint uk_document_counter_type_year unique (document_type, financial_year)
);

create table floors (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone,
    building_id bigint not null,
    floor_name varchar(255) not null,
    carpet_area numeric(38,2),
    chargeable_area numeric(38,2),
    usage varchar(255),
    working_hours varchar(255),
    status varchar(255),
    active boolean not null,
    constraint fk_floor_building foreign key (building_id) references buildings(id)
);

create table floor_prices (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone,
    floor_id bigint not null,
    charge_type varchar(255) not null,
    fixed_rate numeric(38,2),
    per_sq_ft_rate numeric(38,2),
    effective_date date not null,
    escalation_percent numeric(38,2),
    constraint fk_floor_price_floor foreign key (floor_id) references floors(id)
);

create table invoice_types (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone,
    name varchar(255) not null unique,
    prefix varchar(255),
    financial_year_series varchar(255),
    terms varchar(255),
    credit_days integer not null
);

create table sac_hsn_gst (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone,
    code varchar(255) not null unique,
    description varchar(255),
    applicable boolean not null,
    rate numeric(38,2),
    cess numeric(38,2)
);

create table tenant_allotments (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone,
    tenant_id bigint not null,
    floor_id bigint not null,
    agreement_number varchar(255) not null,
    occupancy_start date,
    occupancy_end date,
    deposit numeric(38,2),
    discount numeric(38,2),
    billing_day integer not null,
    lock_in_months integer not null,
    active boolean not null,
    constraint fk_allotment_tenant foreign key (tenant_id) references customers(id),
    constraint fk_allotment_floor foreign key (floor_id) references floors(id)
);

create table tenant_charge_schedule (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone,
    allotment_id bigint not null,
    charge_type varchar(255) not null,
    override_amount numeric(38,2),
    actual_amount numeric(38,2),
    active boolean not null,
    constraint fk_charge_schedule_allotment foreign key (allotment_id) references tenant_allotments(id)
);

create table invoices (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone,
    document_number varchar(255) not null unique,
    tenant_id bigint not null,
    billing_period varchar(255) not null,
    due_date date,
    supply_state varchar(255),
    status varchar(255),
    subtotal numeric(38,2),
    discount numeric(38,2),
    cgst numeric(38,2),
    sgst numeric(38,2),
    igst numeric(38,2),
    cess numeric(38,2),
    tds numeric(38,2),
    total numeric(38,2),
    constraint fk_invoice_tenant foreign key (tenant_id) references customers(id)
);

create index idx_invoice_period_tenant on invoices (billing_period, tenant_id);

create table invoice_lines (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone,
    invoice_id bigint not null,
    charge_type varchar(255),
    description varchar(255),
    sac_hsn_code varchar(255),
    quantity numeric(38,2),
    rate numeric(38,2),
    amount numeric(38,2),
    tax_rate numeric(38,2),
    tax_amount numeric(38,2),
    constraint fk_invoice_line_invoice foreign key (invoice_id) references invoices(id)
);

create table receipts (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone,
    receipt_number varchar(255) not null unique,
    tenant_id bigint not null,
    receipt_date date,
    mode varchar(255),
    amount numeric(38,2),
    unallocated_amount numeric(38,2),
    reference varchar(255),
    constraint fk_receipt_tenant foreign key (tenant_id) references customers(id)
);

create table receipt_allocations (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone,
    receipt_id bigint not null,
    invoice_id bigint not null,
    amount numeric(38,2) not null,
    constraint fk_receipt_allocation_receipt foreign key (receipt_id) references receipts(id),
    constraint fk_receipt_allocation_invoice foreign key (invoice_id) references invoices(id)
);

create table credit_notes (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone,
    document_number varchar(255) not null unique,
    original_invoice_id bigint not null,
    status varchar(255),
    taxable_value numeric(38,2),
    tax_impact numeric(38,2),
    total numeric(38,2),
    reason varchar(255),
    constraint fk_credit_note_invoice foreign key (original_invoice_id) references invoices(id)
);
